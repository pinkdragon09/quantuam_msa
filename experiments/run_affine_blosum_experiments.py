#!/usr/bin/env python3
"""Affine-gap and BLOSUM62 scoring experiments for the MSA path Hamiltonian.

Affine gaps are not column-decomposable, so the exact per-column DP and the
edge-linear QUBO no longer apply.  The energy-search framework, however, only
needs a scoring oracle on whole alignments, so the path-state annealer optimises
affine / BLOSUM62 scores directly.  We validate it against brute-force
enumeration on small instances (the exact optimum under the explicitly defined
pairwise-affine convention ``gap_open + L * gap``) and report DNA and protein
examples.
"""

from __future__ import annotations

import csv
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "experiments"))

import msa_hamiltonian as msa  # noqa: E402

RESULT_DIR = ROOT / "results" / "msa_research"
AFFINE_TABLE = RESULT_DIR / "msa_affine_tables.tex"


def scheme(name: str, scoring: msa.Scoring) -> tuple[str, msa.Scoring]:
    return name, scoring


SCHEMES = [
    scheme("linear_identity", msa.Scoring(match=2, mismatch=-1, gap=-2, gap_open=0)),
    scheme("affine_identity", msa.Scoring(match=2, mismatch=-1, gap=-1, gap_open=-6)),
]
PROTEIN_SCHEMES = [
    scheme("linear_blosum62", msa.Scoring(matrix="blosum62", gap=-2, gap_open=0)),
    scheme("affine_blosum62", msa.Scoring(matrix="blosum62", gap=-1, gap_open=-11)),
]

DNA_INSTANCES = [
    ("dna_a", ("ACGT", "ACT", "ACGT")),
    ("dna_b", ("GATT", "GAT", "GTT")),
]
PROTEIN_INSTANCES = [
    ("prot_a", ("MEEP", "MEP", "MESP")),
    ("prot_b", ("HEAG", "HEG", "HEAG")),
]


def run() -> list[dict[str, str]]:
    rows: list[dict[str, str]] = []
    jobs = [(DNA_INSTANCES, SCHEMES), (PROTEIN_INSTANCES, PROTEIN_SCHEMES)]
    for instances, schemes in jobs:
        for inst_name, seqs in instances:
            for scheme_name, scoring in schemes:
                bf = msa.brute_force_msa(seqs, scoring)
                sa = msa.anneal_msa(
                    seqs, scoring, restarts=50, steps_per_restart=800, seed=13
                )
                rows.append(
                    {
                        "instance": inst_name,
                        "scheme": scheme_name,
                        "k": str(len(seqs)),
                        "lengths": "/".join(str(len(s)) for s in seqs),
                        "alignments_enumerated": str(bf.states_evaluated),
                        "brute_force_score": str(bf.score),
                        "anneal_score": str(sa.score),
                        "anneal_optimal": "yes" if sa.score == bf.score else "no",
                        "optimal_alignment": " | ".join(bf.alignment),
                    }
                )
    return rows


def write_latex(rows: list[dict[str, str]]) -> None:
    def esc(text: str) -> str:
        return text.replace("_", r"\_")

    lines = [
        "% Auto-generated by run_affine_blosum_experiments.py",
        "",
        r"\begin{table}[htbp]",
        r"\centering",
        r"\small",
        r"\begin{tabular}{llrrrc}",
        r"\toprule",
        r"Instance & Scoring scheme & Lengths & Brute-force & Annealer & Optimal \\",
        r"\midrule",
    ]
    for r in rows:
        lines.append(
            f"{esc(r['instance'])} & {esc(r['scheme'])} & {r['lengths']} & "
            f"{r['brute_force_score']} & {r['anneal_score']} & {r['anneal_optimal']} \\\\"
        )
    lines += [
        r"\bottomrule",
        r"\end{tabular}",
        r"\caption{Affine gaps and BLOSUM62 scoring under the convention "
        r"$G(L)=g_{\mathrm{open}}+L g_{\mathrm{ext}}$, so the opening position "
        r"incurs both terms. Affine identity uses "
        r"$g_{\mathrm{open}}=-6$, $g_{\mathrm{ext}}=-1$; affine BLOSUM62 uses "
        r"$g_{\mathrm{open}}=-11$, $g_{\mathrm{ext}}=-1$. Affine costs invalidate "
        r"the unaugmented per-column recurrence and edge-only QUBO, not dynamic "
        r"programming in general. The classical annealer matches exhaustive path "
        r"enumeration on these short instances.}",
        r"\label{tab:affine-blosum}",
        r"\end{table}",
        "",
    ]
    AFFINE_TABLE.write_text("\n".join(lines) + "\n")


def main() -> None:
    RESULT_DIR.mkdir(parents=True, exist_ok=True)
    rows = run()

    with (RESULT_DIR / "affine_blosum.csv").open("w", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=list(rows[0]))
        writer.writeheader()
        writer.writerows(rows)

    write_latex(rows)

    print("Affine-gap / BLOSUM62 scoring experiments")
    print("(brute-force = exact optimum by enumeration; SA = path-state annealer)\n")
    header = f"{'instance':8} {'scheme':16} {'lens':8} {'brute':>6} {'SA':>6} {'opt':>4}"
    print(header)
    print("-" * len(header))
    for r in rows:
        print(
            f"{r['instance']:8} {r['scheme']:16} {r['lengths']:8} "
            f"{r['brute_force_score']:>6} {r['anneal_score']:>6} {r['anneal_optimal']:>4}"
        )

    # Show how affine scoring changes a chosen alignment vs linear.
    print("\nExample -- protein HEAG / HEG / HEAG:")
    seqs = ("HEAG", "HEG", "HEAG")
    for scheme_name, scoring in PROTEIN_SCHEMES:
        bf = msa.brute_force_msa(seqs, scoring)
        print(f"  {scheme_name} (optimum {bf.score}):")
        for row in bf.alignment:
            print(f"      {row}")

    print(f"\nWrote {RESULT_DIR / 'affine_blosum.csv'}")


if __name__ == "__main__":
    main()
