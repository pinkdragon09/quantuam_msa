BLOSUM62: dict[tuple[str, str], int] = {
    (_ORDER[i], _ORDER[j]): _ROWS[i][j]
    for i in range(len(_ORDER))
    for j in range(len(_ORDER))
}


def blosum62(a: str, b: str) -> int:
    """Symmetric BLOSUM62 lookup with an ``X`` fallback for unknown residues."""

    if a == "-" or b == "-":
        raise ValueError(
            "blosum62 is a residue-residue score; gaps must be handled by the "
            "caller's gap penalty, not looked up in the substitution matrix"
        )
    a = a.upper()
    b = b.upper()
    if (a, b) in BLOSUM62:
        return BLOSUM62[(a, b)]
    a = a if (a, "A") in BLOSUM62 else "X"
    b = b if ("A", b) in BLOSUM62 else "X"
    return BLOSUM62[(a, b)]


