#!/usr/bin/env python3
"""Compare our exact ground-state alignments against MAFFT.

MAFFT optimizes a different model, so this script only rescales its output under
the paper's evaluation objective (match/mismatch for DNA, BLOSUM62 for protein,
linear gaps) and compares that score with exact DP. Agreement is not a claim of
biological validity or a benchmark of MAFFT's own objective.

MAFFT is not bundled. The harness finds the binary via the ``MAFFT_BIN``
environment variable or ``mafft`` on ``PATH``; if neither is present it prints
install instructions and exits without error.
"""

from __future__ import annotations

import csv
import os
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "experiments"))

import msa_hamiltonian as msa  # noqa: E402

RESULT_DIR = ROOT / "results" / "msa_research"
MAFFT_TABLE = RESULT_DIR / "msa_mafft_tables.tex"

DNA_SCORING = msa.Scoring(match=2, mismatch=-1, gap=-2, gap_gap=0)
PROTEIN_SCORING = msa.Scoring(matrix="blosum62", gap=-4, gap_gap=0)

DATASETS = [
    ("dna_three_sequence", "DNA", ("ACGTAC", "ACGTC", "ACTTAC")),
    ("protein_three_sequence", "protein", ("MEEPQSD", "MEESQSD", "MEPQSD")),
    ("synthetic_four_sequence", "DNA", ("ACGTACGT", "ACGTTCGT", "ACGACGT", "ACGTACGTT")),
    ("dna_four_gattaca", "DNA", ("GATTACA", "GCATGCA", "GATACA", "GATTACCA")),
    ("dna_four_conserved_block", "DNA", ("TTACGTAA", "TACGTTA", "TTACGTA", "TTACGTTAA")),
    ("protein_HEAG", "protein", ("HEAGAWGHEE", "HEAGAWGHE", "HEAGAWGHEE")),
]


def find_mafft() -> str | None:
    env = os.environ.get("MAFFT_BIN")
    if env and Path(env).exists():
        return env
    return shutil.which("mafft")


def run_mafft(sequences, kind: str, mafft_bin: str) -> tuple[str, ...]:
    """Align sequences with MAFFT and return aligned rows in input order."""

    with tempfile.TemporaryDirectory() as tmp:
        fasta = Path(tmp) / "in.fa"
        fasta.write_text(
            "".join(f">s{i}\n{seq}\n" for i, seq in enumerate(sequences))
        )
        cmd = [mafft_bin, "--quiet", "--auto"]
        cmd += (["--nuc"] if kind == "DNA" else ["--amino"])
        cmd += [str(fasta)]
        out = subprocess.run(cmd, capture_output=True, text=True, check=True).stdout

    # Parse aligned FASTA in the order the records appear (MAFFT preserves input
    # order without --reorder).
    rows: dict[str, list[str]] = {}
    order: list[str] = []
    current = None
    for line in out.splitlines():
        if line.startswith(">"):
            current = line[1:].strip()
            rows[current] = []
            order.append(current)
        elif current is not None:
            rows[current].append(line.strip())
    return tuple("".join(rows[name]).upper() for name in order)


def columns_agree(a: tuple[str, ...], b: tuple[str, ...]) -> bool:
    return len(a) == len(b) and all(x == y for x, y in zip(a, b))


def run() -> list[dict[str, str]]:
    mafft_bin = find_mafft()
    if mafft_bin is None:
        print(
            "MAFFT not found. Install it (e.g. `apt-get install mafft`, "
            "`conda install -c bioconda mafft`, or the portable package from "
            "https://mafft.cbrc.jp/alignment/software/), then set MAFFT_BIN or put "
            "`mafft` on PATH and re-run."
        )
        return []

    print(f"Using MAFFT: {mafft_bin}\n")
    rows: list[dict[str, str]] = []
    for name, kind, seqs in DATASETS:
        scoring = DNA_SCORING if kind == "DNA" else PROTEIN_SCORING
        exact = msa.exact_msa_dp(seqs, scoring)
        mafft_alignment = run_mafft(seqs, kind, mafft_bin)

        # Sanity: removing gaps recovers the inputs.
        recovered = tuple(row.replace("-", "") for row in mafft_alignment)
        if recovered != tuple(seqs):
            raise RuntimeError(f"MAFFT output for {name} does not match inputs")

        mafft_score = msa.score_alignment(mafft_alignment, scoring)
        gap = exact.score - mafft_score
        agree = columns_agree(mafft_alignment, exact.alignment)
        rows.append(
            {
                "dataset": name,
                "type": kind,
                "objective": "match/mismatch" if kind == "DNA" else "BLOSUM62",
                "our_optimum": str(exact.score),
                "mafft_score": str(mafft_score),
                "score_gap": str(gap),
                "mafft_optimal": "yes" if gap == 0 else "no",
                "columns_identical": "yes" if agree else "no",
                "mafft_alignment": " | ".join(mafft_alignment),
                "our_alignment": " | ".join(exact.alignment),
            }
        )
    return rows


def write_latex(rows) -> None:
    def esc(t: str) -> str:
        return t.replace("_", r"\_")

    lines = [
        "% Auto-generated by mafft_comparison.py",
        "",
        r"\begin{table}[htbp]",
        r"\centering",
        r"\small",
        r"\resizebox{\textwidth}{!}{%",
        r"\begin{tabular}{llrrrc}",
        r"\toprule",
        r"Instance & Evaluation objective & Exact score & MAFFT rescored & Gap & "
        r"\shortstack{Matches exact score\\under evaluation objective} \\",
        r"\midrule",
    ]
    for r in rows:
        lines.append(
            f"{esc(r['dataset'])} & {r['objective']} & {r['our_optimum']} & "
            f"{r['mafft_score']} & {r['score_gap']} & {r['mafft_optimal']} \\\\"
        )
    lines += [
        r"\bottomrule",
        r"\end{tabular}",
        r"}",
        r"\caption{MAFFT (v7.526, \texttt{--auto}) outputs rescored under the "
        r"paper's evaluation objective: match $+2$/mismatch $-1$ for DNA or "
        r"BLOSUM62 for protein, with linear gaps. MAFFT optimizes a different "
        r"model; ``yes'' only means its returned alignment matches the exact score "
        r"after rescoring.}",
        r"\label{tab:mafft}",
        r"\end{table}",
        "",
    ]
    MAFFT_TABLE.write_text("\n".join(lines) + "\n")


def write_markdown(rows) -> None:
    lines = [
        "# MAFFT Comparison",
        "",
        "MAFFT v7.526 (`--auto`). Each alignment scored under our sum-of-pairs",
        "objective; our optimum is the exact DP ground state.",
        "",
        "| Dataset | Objective | Our optimum | MAFFT | Gap | MAFFT optimal | Columns identical |",
        "| --- | --- | ---: | ---: | ---: | :--: | :--: |",
    ]
    for r in rows:
        lines.append(
            f"| `{r['dataset']}` | {r['objective']} | {r['our_optimum']} | "
            f"{r['mafft_score']} | {r['score_gap']} | {r['mafft_optimal']} | "
            f"{r['columns_identical']} |"
        )
    (RESULT_DIR / "mafft_comparison.md").write_text("\n".join(lines) + "\n")


def main() -> None:
    RESULT_DIR.mkdir(parents=True, exist_ok=True)
    rows = run()
    if not rows:
        return

    with (RESULT_DIR / "mafft_comparison.csv").open("w", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=list(rows[0]))
        writer.writeheader()
        writer.writerows(rows)
    write_latex(rows)
    write_markdown(rows)

    header = f"{'dataset':26} {'obj':14} {'ours':>5} {'mafft':>6} {'gap':>4} {'opt':>4}"
    print(header)
    print("-" * len(header))
    for r in rows:
        print(
            f"{r['dataset']:26} {r['objective']:14} {r['our_optimum']:>5} "
            f"{r['mafft_score']:>6} {r['score_gap']:>4} {r['mafft_optimal']:>4}"
        )
    print(f"\nWrote {RESULT_DIR / 'mafft_comparison.csv'} and {MAFFT_TABLE}")


if __name__ == "__main__":
    main()
